import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {randomUUID} from 'node:crypto';

test('aviso real de lote: sonido, cierre sin repetición y pantalla móvil',async({page,request})=>{
 const user=JSON.parse(readFileSync(process.env['E2E_CREDENTIALS_PATH']||'.local/demo-user.json','utf8'));
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{
  const original=AudioContext.prototype.createOscillator;
  (window as any).alertTones=0;
  AudioContext.prototype.createOscillator=function(){(window as any).alertTones++;return original.call(this);};
 });
 await page.goto('/login');
 await page.getByLabel('DNI',{exact:true}).fill(user.dni);
 await page.getByLabel('Contraseña',{exact:true}).fill(user.password);
 await Promise.all([page.waitForResponse(r=>r.url().includes('/alerts?state=VENCIDO')&&r.ok()),page.getByRole('button',{name:'Ingresar a mi tienda'}).click()]);
 await expect(page.getByRole('heading',{name:'Resumen',exact:true})).toBeVisible();
 const popup=page.getByRole('alert',{name:'Aviso de vencimiento'});
 if(await popup.isVisible())await popup.getByRole('button',{name:'Cerrar aviso de vencimiento'}).click();
 await page.getByRole('button',{name:'Activar sonido de alertas',exact:true}).click();
 await expect(page.getByRole('button',{name:'Desactivar sonido de alertas'})).toHaveAttribute('aria-pressed','true');
 expect(await page.evaluate(()=>(window as any).alertTones)).toBe(2);
 await Promise.all([page.waitForResponse(r=>r.url().includes('/alerts?state=VENCIDO')&&r.ok()),page.getByRole('button',{name:'Actualizar',exact:false}).first().click()]);
 await expect.poll(()=>page.locator('.critical-popup').count()).toBe(0);
 const csrf=await (await request.get('/api/auth/csrf')).json();
 const login=await request.post('/api/auth/login',{data:user,headers:{'X-XSRF-TOKEN':csrf.token}});
 expect(login.ok()).toBeTruthy();const token=(await login.json()).accessToken;
 const headers={Authorization:'Bearer '+token,'X-XSRF-TOKEN':(await (await request.get('/api/auth/csrf')).json()).token};
 const tag=Date.now().toString();
 const p=await request.post('/api/admin/products',{headers,data:{sku:'AVISO-'+tag,name:'DEMO Yogur aviso sonoro',category:'Lácteos',unit:'UNIDAD',warningDays:30,criticalDays:15,active:true}});
 expect(p.ok()).toBeTruthy();const productId=(await p.json()).id;
 const today=new Date(),tomorrow=new Date(today);tomorrow.setUTCDate(today.getUTCDate()+1);
 const created=await request.post('/api/lots',{headers:{...headers,'X-XSRF-TOKEN':(await (await request.get('/api/auth/csrf')).json()).token,'Idempotency-Key':randomUUID()},data:{productId,code:'AVISO-'+tag,received:today.toISOString().slice(0,10),expiry:tomorrow.toISOString().slice(0,10),quantity:3,cost:2}});
 expect(created.ok(),await created.text()).toBeTruthy();
 await Promise.all([page.waitForResponse(r=>r.url().includes('/alerts?state=VENCIDO')&&r.ok()),page.getByRole('button',{name:'Actualizar',exact:false}).first().click()]);
 await expect(popup).toContainText('AVISO-'+tag);
 await expect(popup).toContainText('Vence mañana');
 expect(await page.evaluate(()=>(window as any).alertTones)).toBe(4);
 await page.screenshot({path:'docs/evidence/expiry-alert-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await expect(page.getByRole('complementary',{name:'Menú principal'})).not.toBeVisible();
 await expect(popup).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'docs/evidence/expiry-alert-mobile.png'});
 await popup.getByRole('button',{name:'Cerrar aviso de vencimiento'}).click();
 await page.setViewportSize({width:1440,height:1000});
 await Promise.all([page.waitForResponse(r=>r.url().includes('/alerts?state=VENCIDO')&&r.ok()),page.getByRole('button',{name:'Actualizar',exact:false}).first().click()]);
 await expect(popup).toHaveCount(0);
 expect(errors).toEqual([]);
});
